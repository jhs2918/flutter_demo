/// [02] 기록작성화면의 카테고리(카드) 하나.
class RecordCategory {
  const RecordCategory({
    required this.id,
    required this.name,
    required this.emoji,
    this.subCategories = const <RecordSubCategory>[],
  });

  // 카테고리 고유 id. 저장소 키로도 사용한다.
  final String id;
  // 카드에 표시할 카테고리 이름.
  final String name;
  // [전면개편] 카드에 표시할 이모지 아이콘.
  final String emoji;
  // [02-02] 카테고리 안의 세부 카테고리 목록.
  final List<RecordSubCategory> subCategories;
}

/// [02-02] 카테고리 안의 세부 카테고리 하나. 기본 제공 버튼을 묶는 단위.
class RecordSubCategory {
  const RecordSubCategory({
    required this.id,
    required this.name,
    this.presetButtons = const <String>[],
  });

  // 세부 카테고리 고유 id. 커스텀 버튼 저장소 키로도 사용한다.
  final String id;
  // 세부 카테고리 이름. 빈 문자열이면 화면에 헤더를 그리지 않는다.
  final String name;
  // 세부 카테고리 기본 제공 버튼. 삭제할 수 없다.
  final List<String> presetButtons;
}

RecordCategory _category(
  String id,
  String name,
  String emoji,
  Map<String, List<String>> groups,
) {
  final List<String> groupNames = groups.keys.toList();
  return RecordCategory(
    id: id,
    name: name,
    emoji: emoji,
    subCategories: List<RecordSubCategory>.generate(
      groupNames.length,
      (int i) => RecordSubCategory(
        id: '${id}_sub_${(i + 1).toString().padLeft(2, '0')}',
        name: groupNames[i],
        presetButtons: groups[groupNames[i]]!,
      ),
    ),
  );
}

